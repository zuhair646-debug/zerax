def _slugify(name: str) -> str:
    """Make a safe Docker/file slug from a project name."""
    import re
    s = (name or "zenrex-project").strip().lower()
    s = re.sub(r"[^a-z0-9]+", "-", s)
    s = re.sub(r"-+", "-", s).strip("-")
    return s or "zenrex-project"


