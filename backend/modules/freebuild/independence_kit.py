async def _generate_architecture_md(project: Dict[str, Any], today: str) -> str:
    """Call Claude to generate a bespoke ARCHITECTURE.md for this project."""
    html = project.get("current_html") or ""
    # Truncate to fit comfortably in Claude's context
    html_preview = html[:8000] if len(html) > 8000 else html
    discovery = (project.get("workflow_state") or {}).get("discovery") or {}
    blueprint = discovery.get("blueprint") or {}
    name = project.get("name") or "Zenrex Project"
    desc = project.get("description") or ""

    user_msg = json.dumps({
        "name": name,
        "description": desc,
        "vertical": blueprint.get("vertical"),
        "vertical_name_ar": blueprint.get("vertical_name_ar"),
        "phases": blueprint.get("phases", [])[:10],
        "essentials": blueprint.get("essentials", [])[:15],
        "html_preview_first_8k_chars": html_preview,
        "html_size_bytes": len(html),
        "today": today,
    }, ensure_ascii=False)

    sys_prompt = _ARCHITECTURE_SYSTEM_PROMPT.format(today=today)
    try:
        text = await ask_claude(
            system=sys_prompt,
            user_message=user_msg,
            max_tokens=4096,
            timeout=110.0,
        )
        return (text or "").strip() or _fallback_architecture(name, today)
    except Exception as e:  # noqa: BLE001
        _logger.warning(
            "architecture_md generation failed (%s: %s) — using fallback",
            type(e).__name__, str(e) or "<empty>",
        )
        return _fallback_architecture(name, today)


